def test_positive_feature(page):
    page.goto("https://asi.paygov.org.in/")
    expect(page.get_by_text("ARCHAEOLOGICAL SURVEY OF INDIA", exact=True).first).to_be_visible()
    page.first.check_delhi()
    check_checkbox(page, "Jantar Mantar")
    select_dropdown(page, "Visit time", "Afternoon")
    page.secnd.click_proceed_to_pay()
    expect(page.get_by_text("Note: Adult age above 15 yrs & child age below 15 yrs", exact=True).first).to_be_visible()
    page.secnd.enter_name("abcd")
    page.secnd.enter_age("33")
    page.secnd.enter_email("asfb@gmail.com")
    page.secnd.enter_mobile_no("7897852147")
    page.secnd.click_proceed_to_pay()
    page.third.enter_card_number("473424243342")
    page.third.select_expiry_month_mm("12")
    page.third.select_expiry_year_yyyy("2033")
    page.third.enter_name_on_card("Abcd")
    page.third.enter_cvv("123")
    page.third.click_pay_now()

